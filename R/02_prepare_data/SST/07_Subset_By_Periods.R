# ── fill_na_local_mean ────────────────────────────────────────────────────────
# Purpose: Fills NA values in a numeric vector using the mean of up to k
#          non-NA neighbors on each side. Applied to migration dates to handle
#          cohort years with missing telemetry data.
# Parameters:
#   x  : numeric vector, possibly containing NAs
#   k  : integer, number of neighbors to consider on each side (default = 5)
# Returns: numeric vector with NAs replaced by rounded local means.

fill_na_local_mean <- function(x, k = 5) {
  for (i in seq_along(x)) {
    if (is.na(x[i])) {
      i_min     <- max(1, i - k)
      i_max     <- min(length(x), i + k)
      neighbors <- x[i_min:i_max]
      neighbors <- neighbors[!is.na(neighbors)]
      if (length(neighbors) > 0) x[i] <- round(mean(neighbors))
    }
  }
  return(x)
}


# ── load_polygon_data ─────────────────────────────────────────────────────────
# Purpose: Loads and concatenates all monthly TH .fst files for a given
#          spatial polygon into a single data.table sorted by date.
# Parameters:
#   poly_name : character, name of the polygon (matches folder suffix)
# Returns: data.table of daily TH values across all available months,
#          or NULL with a warning if no files are found.

load_polygon_data <- function(poly_name) {
  poly_dir <- file.path(index_dir, paste0("SST_Index_", poly_name))
  files    <- list.files(poly_dir, pattern = "TH_\\d{4}_\\d{2}\\.fst$",
                         full.names = TRUE)
  if (length(files) == 0) {
    warning("No files found for polygon: ", poly_name)
    return(NULL)
  }
  dt <- rbindlist(lapply(files, read_fst, as.data.table = TRUE), fill = TRUE)
  setorder(dt, date)
  dt
}


# ── build_windows_subpolygons ─────────────────────────────────────────────────
# Purpose: Divides the migration window of each cohort into n equal sub-windows,
#          one per spatial sub-polygon (FID). Used for corridor polygons where
#          fish progress through spatially ordered segments.
# Parameters:
#   dates_df      : data.frame with cohort, entry, and exit columns
#   entry_col     : character, name of the entry date column
#   exit_col      : character, name of the exit date column
#   river_name    : character, river identifier ("stj" or "tri")
#   n_subpolygons : integer, number of FID sub-polygons to split into
# Returns: data.frame with one row per cohort x FID combination, containing
#          cohort, entry date, exit date, river, and FID.

build_windows_subpolygons <- function(dates_df, entry_col, exit_col,
                                      river_name, n_subpolygons) {
  dates_df <- dates_df %>%
    dplyr::select(cohort, entry = all_of(entry_col),
                  exit  = all_of(exit_col)) %>%
    dplyr::filter(!is.na(entry), !is.na(exit))
  
  dates_df_list_year_i <- list()
  
  for (i in seq_len(nrow(dates_df))) {
    all_dates_year_i <- seq(from = dates_df$entry[i],
                            to   = dates_df$exit[i])
    base_days  <- length(all_dates_year_i) %/% n_subpolygons
    extra_days <- length(all_dates_year_i) %% n_subpolygons
    cut_points <- cumsum(c(base_days +
                             c(rep(1, extra_days),
                               rep(0, n_subpolygons - extra_days))))
    start_idx  <- c(1, cut_points[-n_subpolygons] + 1)
    end_idx    <- cut_points
    
    sub_list <- list()
    for (j in seq_along(start_idx)) {
      sub_list[[j]] <- data.frame(
        cohort = dates_df$cohort[i],
        entry  = all_dates_year_i[start_idx[j]],
        exit   = all_dates_year_i[end_idx[j]],
        river  = river_name,
        FID    = j
      )
    }
    dates_df_list_year_i[[i]] <- bind_rows(sub_list)
  }
  bind_rows(dates_df_list_year_i)
}


# ── compute_simple_polygon_TH ─────────────────────────────────────────────────
# Purpose: Sums daily TH values within the migration window for each cohort,
#          for polygons that are not spatially subdivided (no FID split).
# Parameters:
#   poly_dt   : data.table of daily TH values for a polygon
#   dates_df  : data.frame with cohort, entry, and exit date columns
#   entry_col : character, name of the entry DOY column
#   exit_col  : character, name of the exit DOY column
#   poly_name : character, prefix used to name output columns
# Returns: data.table with one row per cohort and two columns:
#          <poly_name>_TH_1SW and <poly_name>_TH_2SW.

compute_simple_polygon_TH <- function(poly_dt, dates_df,
                                      entry_col, exit_col,
                                      poly_name) {
  if (is.null(poly_dt)) return(NULL)
  
  dates_dt <- as.data.table(dates_df)[, .(
    cohort,
    entry_doy = get(entry_col),
    exit_doy  = get(exit_col)
  )]
  dates_dt <- dates_dt[!is.na(entry_doy) & !is.na(exit_doy)]
  
  result_list <- vector("list", nrow(dates_dt))
  
  for (i in seq_len(nrow(dates_dt))) {
    cohort_i <- dates_dt$cohort[i]
    entry_i  <- dates_dt$entry_doy[i]
    exit_i   <- dates_dt$exit_doy[i]
    
    sub <- poly_dt[year == cohort_i &
                     doy >= entry_i &
                     doy <= exit_i]
    
    if (nrow(sub) == 0) {
      result_list[[i]] <- data.table(
        cohort = cohort_i,
        TH_1SW = NA_real_,
        TH_2SW = NA_real_
      )
    } else {
      result_list[[i]] <- data.table(
        cohort = cohort_i,
        TH_1SW = sum(sub$TH_1SW_sum, na.rm = TRUE),
        TH_2SW = sum(sub$TH_2SW_sum, na.rm = TRUE)
      )
    }
  }
  
  out <- rbindlist(result_list)
  setnames(out, c("TH_1SW", "TH_2SW"),
           c(paste0(poly_name, "_TH_1SW"),
             paste0(poly_name, "_TH_2SW")))
  out
}


# ── compute_corridor_TH ───────────────────────────────────────────────────────
# Purpose: Sums daily TH values within the migration window for each cohort,
#          for corridor polygons subdivided into FID sub-segments. Days are
#          assigned to FIDs proportionally, then summed across all FIDs.
# Parameters:
#   poly_dt       : data.table of daily TH values for the corridor polygon
#   dates_df      : data.frame with cohort, entry, and exit date columns
#   entry_col     : character, name of the entry DOY column
#   exit_col      : character, name of the exit DOY column
#   river_name    : character, river identifier ("stj" or "tri")
#   n_subpolygons : integer, number of FID sub-polygons
#   poly_name     : character, prefix used to name output columns
# Returns: data.table with one row per cohort and two columns:
#          <poly_name>_TH_1SW and <poly_name>_TH_2SW.

compute_corridor_TH <- function(poly_dt, dates_df,
                                entry_col, exit_col,
                                river_name, n_subpolygons,
                                poly_name) {
  if (is.null(poly_dt)) return(NULL)
  
  windows <- as.data.table(
    build_windows_subpolygons(dates_df, entry_col, exit_col,
                              river_name, n_subpolygons)
  )
  
  result_list <- vector("list", nrow(windows))
  
  for (i in seq_len(nrow(windows))) {
    cohort_i <- windows$cohort[i]
    entry_i  <- windows$entry[i]
    exit_i   <- windows$exit[i]
    fid_i    <- windows$FID[i]
    
    sub <- poly_dt[year == cohort_i &
                     doy  >= entry_i &
                     doy  <= exit_i  &
                     FID  == as.character(fid_i)]
    
    result_list[[i]] <- data.table(
      cohort = cohort_i,
      TH_1SW = if (nrow(sub) > 0) sum(sub$TH_1SW_sum, na.rm = TRUE) else NA_real_,
      TH_2SW = if (nrow(sub) > 0) sum(sub$TH_2SW_sum, na.rm = TRUE) else NA_real_
    )
  }
  
  # Sum across all FIDs per cohort to get a single annual index
  all_fids <- rbindlist(result_list)
  out <- all_fids[, .(TH_1SW = sum(TH_1SW, na.rm = TRUE),
                      TH_2SW = sum(TH_2SW, na.rm = TRUE)),
                  by = cohort]
  
  setnames(out, c("TH_1SW", "TH_2SW"),
           c(paste0(poly_name, "_TH_1SW"),
             paste0(poly_name, "_TH_2SW")))
  out
}


# ── compute_labrador_TH ───────────────────────────────────────────────────────
# Purpose: Sums Labrador Sea TH across cross-year windows. For 1SW fish, the
#          window spans cohort year through cohort+1. For 2SW fish, it spans
#          cohort year through cohort+2, applying the 6-14 C thermal range
#          (TH_1SW_sum) during the first sea-year and the 6-12 C range
#          (TH_2SW_sum) after the 1SW return date.
# Parameters:
#   lab_dt   : data.table of daily TH values for the Labrador Sea polygon
#   dates_df : data.frame with cohort-level migration dates including
#              lab_sea_entry, lab_sea_exit_1sw, and lab_sea_exit_2sw columns
# Returns: data.table with one row per cohort and two columns:
#          LabradorSea_TH_1SW and LabradorSea_TH_2SW.

compute_labrador_TH <- function(lab_dt, dates_df) {
  if (is.null(lab_dt)) return(NULL)
  
  dates_dt <- as.data.table(dates_df)[, .(
    cohort,
    entry_doy    = lab_sea_entry,
    exit_doy_1sw = lab_sea_exit_1sw,
    exit_doy_2sw = lab_sea_exit_2sw
  )]
  dates_dt <- dates_dt[!is.na(entry_doy)]
  
  result_list <- vector("list", nrow(dates_dt))
  
  for (i in seq_len(nrow(dates_dt))) {
    cohort_i    <- dates_dt$cohort[i]
    entry_doy_i <- dates_dt$entry_doy[i]
    exit_1sw_i  <- dates_dt$exit_doy_1sw[i]
    exit_2sw_i  <- dates_dt$exit_doy_2sw[i]
    
    # 1SW: entry to Dec 31 of cohort year, then Jan 1 to exit of cohort+1
    sub_1sw_yr0 <- lab_dt[year == cohort_i   & doy >= entry_doy_i]
    sub_1sw_yr1 <- lab_dt[year == cohort_i+1 & doy <= exit_1sw_i]
    TH_1SW <- sum(c(sub_1sw_yr0$TH_1SW_sum,
                    sub_1sw_yr1$TH_1SW_sum), na.rm = TRUE)
    
    # 2SW: four segments across three calendar years, switching thermal range
    # at the 1SW return date (from 6-14 C to 6-12 C range)
    sub_2sw_yr0 <- lab_dt[year == cohort_i   & doy >= entry_doy_i]
    sub_2sw_yr1 <- lab_dt[year == cohort_i+1 & doy <  exit_1sw_i]
    sub_2sw_yr2 <- lab_dt[year == cohort_i+1 & doy >= exit_1sw_i]
    sub_2sw_yr3 <- lab_dt[year == cohort_i+2 & doy <= exit_2sw_i]
    TH_2SW <- sum(c(sub_2sw_yr0$TH_1SW_sum,  # entry to Dec 31 yr0  : 6-14 C range
                    sub_2sw_yr1$TH_1SW_sum,   # Jan 1 to 1SW return  : 6-14 C range
                    sub_2sw_yr2$TH_2SW_sum,   # 1SW return to Dec 31 : 6-12 C range
                    sub_2sw_yr3$TH_2SW_sum),  # Jan 1 to 2SW return  : 6-12 C range
                  na.rm = TRUE)
    
    result_list[[i]] <- data.table(
      cohort             = cohort_i,
      LabradorSea_TH_1SW = TH_1SW,
      LabradorSea_TH_2SW = TH_2SW
    )
  }
  
  rbindlist(result_list)
}


# ── merge_all ─────────────────────────────────────────────────────────────────
# Purpose: Sequentially merges a list of per-cohort data.tables on the
#          "cohort" key using a full outer join.
# Parameters:
#   dt_list : list of data.tables, each containing a "cohort" column
# Returns: single data.table with all columns merged by cohort.

merge_all <- function(dt_list) {
  dt_list <- Filter(Negate(is.null), dt_list)
  Reduce(function(a, b) merge(a, b, by = "cohort", all = TRUE), dt_list)
}


