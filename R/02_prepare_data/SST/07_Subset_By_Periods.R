# Computes annual thermal habitat indices (TH) for Atlantic salmon during the
# marine phase. For each cohort x river x sea-age combination, daily TH values
# are summed within biologically defined migration windows across five spatial
# polygons: the migration corridor, Belle Isle Strait, Labrador Entrance,
# and the Labrador Sea (the latter with a cross-year accumulation for 2SW fish).
#
# Inputs:
#   - R/01_derived_data/SST_Index/SST_Index_<polygon>/TH_<YYYY>_<MM>.fst
#       Monthly daily TH data per spatial polygon [fst, one file per month]
#   - R/01_derived_data/Year_Migration_Dates_River_Sea.fst
#       Per-cohort migration window dates for STJ and TRI [fst]
#
# Outputs:
#   - R/03_clean_data/Sea/TH_annual_stj_1sw.fst  [fst]
#   - R/03_clean_data/Sea/TH_annual_stj_2sw.fst  [fst]
#   - R/03_clean_data/Sea/TH_annual_tri_1sw.fst  [fst]
#   - R/03_clean_data/Sea/TH_annual_tri_2sw.fst  [fst]
# ══════════════════════════════════════════════════════════════════════════════


