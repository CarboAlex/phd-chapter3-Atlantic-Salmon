# ── Data quality checks ───────────────────────────────────────────────────────
# Verify date continuity and absence of NA in TH columns for each polygon.

check_dates <- function(data_dt) {
  all_dates  <- seq(min(data_dt$date), max(data_dt$date), by = "day")
  missing_dates <- all_dates[!all_dates %in% data_dt$date]
  cat("Missing dates:", length(missing_dates), "\n")
  if (length(missing_dates) > 0) print(missing_dates)
}

check_NA <- function(data_dt) {
  cat("NA in TH_1SW_sum:", sum(is.na(data_dt$TH_1SW_sum)), "\n")
  cat("NA in TH_2SW_sum:", sum(is.na(data_dt$TH_2SW_sum)), "\n")
}

